const LanguageContext = createContext<{
  locale: SupportedLocale
  setLocale: (nextLocale: SupportedLocale) => void
}>({
  locale: 'tr',
  setLocale: () => {},
})

const STORAGE_KEY = 'pulbi_locale'

const getBestLocale = (): SupportedLocale => {
  if (typeof navigator === 'undefined') return 'tr'
  const nav = navigator.language.toLowerCase()
  const matched = supportedLocales.find((locale) => nav.startsWith(locale))
  return matched ?? 'tr'
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<SupportedLocale>('tr')

  useEffect(() => {
    const saved = typeof window !== 'undefined' ? window.localStorage.getItem(STORAGE_KEY) : null
    if (saved && supportedLocales.includes(saved as SupportedLocale)) {
      setLocaleState(saved as SupportedLocale)
      return
    }

    setLocaleState(getBestLocale())
  }, [])

  useEffect(() => {
    if (typeof window === 'undefined') return
    document.documentElement.lang = locale
    window.localStorage.setItem(STORAGE_KEY, locale)
  }, [locale])

  const setLocale = (nextLocale: SupportedLocale) => {
    setLocaleState(nextLocale)
  }

  const value = useMemo(
    () => ({ locale, setLocale }),
    [locale]
  )

  return createElement(LanguageContext.Provider, { value }, children)
}

export function useLanguage() {
  return useContext(LanguageContext)
}

export function useTranslations() {
  const { locale } = useLanguage()

  return useCallback((key: string, params?: Record<string, string | number>) => {
    const localeStrings = translations[locale] || translations.tr
    let text = localeStrings[key] ?? translations.tr[key] ?? key
    if (params) {
      for (const [paramKey, paramValue] of Object.entries(params)) {
        text = text.replace(`{${paramKey}}`, String(paramValue))
      }
    }
    return text
  }, [locale])
}